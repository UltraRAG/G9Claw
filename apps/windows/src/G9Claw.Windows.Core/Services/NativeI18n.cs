using System.Globalization;

namespace G9Claw.Windows.Core;

public static class NativeI18nLanguageResolver
{
    public static string Resolve(AppLanguage language, CultureInfo? culture = null)
    {
        return language switch
        {
            AppLanguage.English => "en",
            AppLanguage.ChineseSimplified => "zh-CN",
            _ => (culture ?? CultureInfo.CurrentUICulture).Name.StartsWith("zh", StringComparison.OrdinalIgnoreCase)
                ? "zh-CN"
                : "en",
        };
    }
}

public sealed class StringCatalog
{
    private readonly string _language;

    public StringCatalog(AppLanguage language, CultureInfo? culture = null)
    {
        _language = NativeI18nLanguageResolver.Resolve(language, culture);
    }

    public string T(string key)
    {
        if (_language == "zh-CN")
        {
            if (CleanChinese.TryGetValue(key, out var cleanChinese)) return cleanChinese;
            if (FixedChinese.TryGetValue(key, out var fixedChinese)) return fixedChinese;
            if (Translations.TryGetValue(("en", key), out var englishFallback)) return englishFallback;
        }

        if (Translations.TryGetValue((_language, key), out var localized)) return localized;
        if (Translations.TryGetValue(("en", key), out var english)) return english;
        return key;
    }

    public static bool HasKey(string language, string key) => Translations.ContainsKey((language, key));

